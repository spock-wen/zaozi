#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""生成 entry/src/main/cangjie/glyph_data.cj（GENERATED，勿手改）。

数据来源：glyph/glyph_pack_v1.csv（GLYPH_PACK_V1，106 行 / 27 字）。
每行 CSV 产出一条 GlyphRow，顺序与 CSV 一致：

    id, char, trad, method, order, stage, stage_label, format,
    csvPath（CSV 的 path 列，只作出处记录）,
    asset（"glyph/<id>_<stage>.<svg|png 小写>"，App 内 rawfile 路径）,
    sha1, creditNote, sourceLabel（出处标签）, license（许可）

asset 命名约定：normalized/<id>_<stage>.<ext>，stage 取 CSV 的 stage 列
（oracle / bronze / seal / clerical）。 coordinator 按这个约定投放文件，
本脚本只按 CSV 推导，不依赖 normalized/ 是否存在。

纯 stdlib。用法：
    python3 tools/gen_glyph_catalog.py [--csv PATH] [--out PATH]
"""
import argparse
import csv
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)

DEFAULT_CSV = os.path.join(
    REPO, "entry", "src", "main", "resources", "rawfile", "glyph", "glyph_pack_v1.csv"
)
DEFAULT_OUT = os.path.join(REPO, "entry", "src", "main", "cangjie", "glyph_data.cj")
DEFAULT_RES_OUT = os.path.join(REPO, "entry", "src", "main", "cangjie", "glyph_res.cj")

EXPECTED_ROWS = 106
VALID_STAGES = ("oracle", "bronze", "seal", "clerical")
VALID_FORMATS = ("SVG", "PNG")


def cj_string(value):
    """Cangjie 字符串字面量（转义反斜杠与双引号）。"""
    return '"%s"' % value.replace("\\", "\\\\").replace('"', '\\"')


def asset_name(row):
    """CSV 行 → App 内 rawfile 资源名 glyph/<id>_<stage>.<ext>。"""
    ext = row["format"].strip().lower()
    return "glyph/%s_%s.%s" % (row["id"].strip(), row["stage"].strip(), ext)


def read_rows(csv_path):
    with open(csv_path, "r", encoding="utf-8", newline="") as fh:
        return list(csv.DictReader(fh))


def check_rows(rows):
    """返回错误列表（空 = 通过）。"""
    errs = []
    if len(rows) != EXPECTED_ROWS:
        errs.append("行数 %d != %d" % (len(rows), EXPECTED_ROWS))
    seen = set()
    for i, row in enumerate(rows):
        rid = (row.get("id") or "").strip()
        stage = (row.get("stage") or "").strip()
        fmt = (row.get("format") or "").strip()
        where = "第 %d 行 (%s/%s)" % (i + 2, rid, stage)
        for col in ("id", "char", "trad", "method", "order", "stage",
                    "stage_label", "format", "path", "sha1"):
            if not (row.get(col) or "").strip():
                errs.append("%s：列 %s 为空" % (where, col))
        if stage not in VALID_STAGES:
            errs.append("%s：stage %r 不在 %s" % (where, stage, list(VALID_STAGES)))
        if fmt not in VALID_FORMATS:
            errs.append("%s：format %r 不是 SVG/PNG" % (where, fmt))
        key = (rid, stage)
        if key in seen:
            errs.append("%s：重复的 (id, stage)" % where)
        seen.add(key)
    return errs


def emit(rows, out_path):
    lines = []
    lines.append("package ohos_app_cangjie_entry")
    lines.append("")
    lines.append("/* GENERATED by tools/gen_glyph_catalog.py — 勿手改。")
    lines.append("   来源：glyph/glyph_pack_v1.csv（GLYPH_PACK_V1，%d 行 / 27 字）。" % len(rows))
    lines.append("   重新生成：python3 tools/sync_glyphs.py")
    lines.append("   只放纯数据：不 import 任何 kit/ohos 模块，因此能在普通 Linux 上用")
    lines.append("   cjc 编译验证（见 tools/box_check）。")
    lines.append("   csvPath 只作出处记录；App 实际加载 asset 列的 rawfile 路径。 */")
    lines.append("")
    lines.append("import std.collection.ArrayList")
    lines.append("")
    lines.append("/* 一个字的一个阶段。字段与 CSV 列一一对应：")
    lines.append("   CSV 的 char 列在本文件里叫 glyph（char 与关键字冲突）。 */")
    lines.append("public class GlyphRow {")
    lines.append("    public let id: String")
    lines.append("    public let glyph: String")
    lines.append("    public let trad: String")
    lines.append("    public let method: String")
    lines.append("    public let order: Int64")
    lines.append("    public let stage: String")
    lines.append("    public let stageLabel: String")
    lines.append("    public let format: String")
    lines.append("    public let csvPath: String")
    lines.append("    public let asset: String")
    lines.append("    public let sha1: String")
    lines.append("    public let creditNote: String")
    lines.append("    public let sourceLabel: String")
    lines.append("    public let license: String")
    lines.append("")
    lines.append("    public init(")
    lines.append("        id: String,")
    lines.append("        glyph: String,")
    lines.append("        trad: String,")
    lines.append("        method: String,")
    lines.append("        order: Int64,")
    lines.append("        stage: String,")
    lines.append("        stageLabel: String,")
    lines.append("        format: String,")
    lines.append("        csvPath: String,")
    lines.append("        asset: String,")
    lines.append("        sha1: String,")
    lines.append("        creditNote: String,")
    lines.append("        sourceLabel: String,")
    lines.append("        license: String")
    lines.append("    ) {")
    lines.append("        this.id = id")
    lines.append("        this.glyph = glyph")
    lines.append("        this.trad = trad")
    lines.append("        this.method = method")
    lines.append("        this.order = order")
    lines.append("        this.stage = stage")
    lines.append("        this.stageLabel = stageLabel")
    lines.append("        this.format = format")
    lines.append("        this.csvPath = csvPath")
    lines.append("        this.asset = asset")
    lines.append("        this.sha1 = sha1")
    lines.append("        this.creditNote = creditNote")
    lines.append("        this.sourceLabel = sourceLabel")
    lines.append("        this.license = license")
    lines.append("    }")
    lines.append("}")
    lines.append("")
    lines.append("/* CSV 行序（= order 分组后的顺序）原样落成数据。 */")
    lines.append("public func buildGlyphRows(): ArrayList<GlyphRow> {")
    lines.append("    let rows = ArrayList<GlyphRow>()")
    for row in rows:
        lines.append(
            "    rows.add(GlyphRow(%s, %s, %s, %s, %d, %s, %s, %s, %s, %s, %s, %s, %s, %s))" % (
                cj_string(row["id"].strip()),
                cj_string(row["char"].strip()),
                cj_string(row["trad"].strip()),
                cj_string(row["method"].strip()),
                int(row["order"].strip()),
                cj_string(row["stage"].strip()),
                cj_string(row["stage_label"].strip()),
                cj_string(row["format"].strip()),
                cj_string(row["path"].strip()),
                cj_string(asset_name(row)),
                cj_string(row["sha1"].strip()),
                cj_string((row.get("credit_note") or "").strip()),
                cj_string((row.get("source_label") or "").strip()),
                cj_string((row.get("license") or "").strip()),
            )
        )
    lines.append("    return rows")
    lines.append("}")
    lines.append("")
    lines.append("/* 全局唯一一份数据； GlyphCatalog 只读它。 */")
    lines.append("public let GLYPH_ROWS: ArrayList<GlyphRow> = buildGlyphRows()")
    lines.append("")
    lines.append("public class GlyphCatalog {")
    lines.append("    /* 全部行（CSV 顺序）。 */")
    lines.append("    public static func all(): ArrayList<GlyphRow> {")
    lines.append("        return GLYPH_ROWS")
    lines.append("    }")
    lines.append("")
    lines.append("    public static func count(): Int64 {")
    lines.append("        return GLYPH_ROWS.size")
    lines.append("    }")
    lines.append("")
    lines.append("    public static func byIndex(index: Int64): GlyphRow {")
    lines.append("        return GLYPH_ROWS[index]")
    lines.append("    }")
    lines.append("")
    lines.append("    /* 一个字的全部阶段，按 order 升序（缺的阶段本来就不在表里）。 */")
    lines.append("    public static func ofChar(id: String): ArrayList<GlyphRow> {")
    lines.append("        let out = ArrayList<GlyphRow>()")
    lines.append("        var i: Int64 = 0")
    lines.append("        while (i < GLYPH_ROWS.size) {")
    lines.append("            if (GLYPH_ROWS[i].id == id) {")
    lines.append("                out.add(GLYPH_ROWS[i])")
    lines.append("            }")
    lines.append("            i = i + 1")
    lines.append("        }")
    lines.append("        var a: Int64 = 1")
    lines.append("        while (a < out.size) {")
    lines.append("            let cur = out[a]")
    lines.append("            var b: Int64 = a - 1")
    lines.append("            while (b >= 0 && out[b].order > cur.order) {")
    lines.append("                out[b + 1] = out[b]")
    lines.append("                b = b - 1")
    lines.append("            }")
    lines.append("            out[b + 1] = cur")
    lines.append("            a = a + 1")
    lines.append("        }")
    lines.append("        return out")
    lines.append("    }")
    lines.append("")
    lines.append("    /* 字表（CSV 里首次出现的顺序），27 字。 */")
    lines.append("    public static func charIds(): ArrayList<String> {")
    lines.append("        let out = ArrayList<String>()")
    lines.append("        var i: Int64 = 0")
    lines.append("        while (i < GLYPH_ROWS.size) {")
    lines.append("            let id = GLYPH_ROWS[i].id")
    lines.append("            var seen: Bool = false")
    lines.append("            var j: Int64 = 0")
    lines.append("            while (j < out.size) {")
    lines.append("                if (out[j] == id) {")
    lines.append("                    seen = true")
    lines.append("                }")
    lines.append("                j = j + 1")
    lines.append("            }")
    lines.append("            if (!seen) {")
    lines.append("                out.add(id)")
    lines.append("            }")
    lines.append("            i = i + 1")
    lines.append("        }")
    lines.append("        return out")
    lines.append("    }")
    lines.append("")
    lines.append("    /* asset → 行下标，找不到返回 -1。 */")
    lines.append("    public static func indexOfAsset(asset: String): Int64 {")
    lines.append("        var i: Int64 = 0")
    lines.append("        while (i < GLYPH_ROWS.size) {")
    lines.append("            if (GLYPH_ROWS[i].asset == asset) {")
    lines.append("                return i")
    lines.append("            }")
    lines.append("            i = i + 1")
    lines.append("        }")
    lines.append("        return -1")
    lines.append("    }")
    lines.append("}")
    lines.append("")

    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    return len(lines)


def emit_res(rows, out_path):
    """生成 entry/src/main/cangjie/glyph_res.cj（GENERATED，勿手改）。

    每个字形一条字面量 case：asset 字符串 → @rawfile("同一个字符串")。
    这样 App 里就能直接用 glyphResource(cell.asset) 拿 AppResource，
    而不必在运行期拼资源 id（ohos 侧没有按名查 rawfile 的公共 API）。

    这是唯一需要 kit/ohos 的生成文件：本机没有 ohos SDK，编不了，
    只做语法检查（tools/box_check/parse_check.sh）。
    """
    fallback = asset_name(rows[0])
    lines = []
    lines.append("package ohos_app_cangjie_entry")
    lines.append("")
    lines.append("/* GENERATED by tools/gen_glyph_catalog.py — 勿手改。")
    lines.append("   来源：glyph/glyph_pack_v1.csv（GLYPH_PACK_V1，%d 行 / 27 字）。" % len(rows))
    lines.append("   重新生成：python3 tools/sync_glyphs.py")
    lines.append("")
    lines.append("   asset 字符串 → @rawfile 字面量，一行一条。@rawfile 的实参必须")
    lines.append("   是编译期常量，所以只能这样穷举，不能运行时拼路径。")
    lines.append("   取不到时退回第一条（%s）。" % fallback)
    lines.append("")
    lines.append("   依赖 ohos kit（AppResource / @rawfile），本机没有 ohos SDK 编不了，")
    lines.append("   只做语法检查：bash tools/box_check/parse_check.sh */")
    lines.append("")
    lines.append("import ohos.resource.AppResource")
    # @rawfile 在 SDK 里挂在 ohos.arkui.state_macro_manage 下；
    # ohos.state_macro_manage 这个包不存在（DevEco 报
    # can not find the following dependencies），所以用 arkui 这条。
    lines.append("import ohos.arkui.state_macro_manage.*")
    lines.append("")
    lines.append("/* rawfile 里的字形资源（resources/rawfile/glyph/<id>_<stage>.<ext>）。")
    lines.append("   cell.asset 就是 GlyphRow.asset，见 glyph_data.cj。 */")
    lines.append("public func glyphResource(asset: String): AppResource {")
    lines.append("    match (asset) {")
    for row in rows:
        a = asset_name(row)
        lines.append("        case %s => @rawfile(%s)" % (cj_string(a), cj_string(a)))
    lines.append("        case _ => @rawfile(%s)" % cj_string(fallback))
    lines.append("    }")
    lines.append("}")
    lines.append("")

    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    return len(lines)


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--csv", default=DEFAULT_CSV)
    ap.add_argument("--out", default=DEFAULT_OUT)
    ap.add_argument("--res-out", default=DEFAULT_RES_OUT,
                    help="glyph_res.cj 输出路径（@rawfile 映射）")
    args = ap.parse_args(argv)

    if not os.path.isfile(args.csv):
        print("ERROR: 找不到 CSV：%s" % args.csv)
        return 1
    rows = read_rows(args.csv)
    errs = check_rows(rows)
    if errs:
        print("ERROR: CSV 校验未过：")
        for e in errs:
            print("  - %s" % e)
        return 1
    n = emit(rows, args.out)
    print("glyph_catalog: %d 行 → %s（%d 行 Cangjie）" % (len(rows), args.out, n))
    if args.res_out:
        m = emit_res(rows, args.res_out)
        print("glyph_res: %d 个 @rawfile case → %s（%d 行 Cangjie）"
              % (len(rows), args.res_out, m))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
