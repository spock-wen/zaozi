export function readLocale() {
  try {
    const v = localStorage.getItem(LOCALE_KEY);
    if (v === "zh" || v === "en") return v;
  } catch { /* 隐私模式当中文 */ }
  return "zh";
}

/** @param {string} locale @param {string} key @param {Record<string, string|number>=} vars */
export function lookupCopy(locale, key, vars) {
  const pack = UI_COPY[locale] || UI_COPY.zh;
  let s = pack[key];
  if (s == null || s === "") s = UI_COPY.zh[key];
  if (s == null) return key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

